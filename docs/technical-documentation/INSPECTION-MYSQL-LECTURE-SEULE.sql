-- Préparé pour un opérateur disposant déjà d'un accès autorisé.
-- Aucune exécution pendant la mission ; aucune instruction d'écriture.
SELECT VERSION(), CURRENT_USER(), DATABASE(), @@session.time_zone;
SHOW GRANTS FOR CURRENT_USER;
SELECT TABLE_NAME,TABLE_TYPE,ENGINE,TABLE_COLLATION FROM information_schema.TABLES
 WHERE TABLE_SCHEMA='secure_payroll' ORDER BY TABLE_NAME;
SELECT TABLE_NAME,ORDINAL_POSITION,COLUMN_NAME,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT,EXTRA,GENERATION_EXPRESSION
 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='secure_payroll' ORDER BY TABLE_NAME,ORDINAL_POSITION;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,ENFORCED FROM information_schema.TABLE_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA='secure_payroll' ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT TABLE_NAME,CONSTRAINT_NAME,COLUMN_NAME,ORDINAL_POSITION,REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME
 FROM information_schema.KEY_COLUMN_USAGE WHERE CONSTRAINT_SCHEMA='secure_payroll'
 ORDER BY TABLE_NAME,CONSTRAINT_NAME,ORDINAL_POSITION;
SELECT TABLE_NAME,CONSTRAINT_NAME,UPDATE_RULE,DELETE_RULE FROM information_schema.REFERENTIAL_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA='secure_payroll' ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT CONSTRAINT_NAME,CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA='secure_payroll' ORDER BY CONSTRAINT_NAME;
SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME,INDEX_TYPE
 FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='secure_payroll' ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX;
SELECT ROUTINE_NAME,ROUTINE_TYPE,DEFINER,SECURITY_TYPE,SQL_DATA_ACCESS,ROUTINE_DEFINITION
 FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA='secure_payroll' ORDER BY ROUTINE_NAME;
SELECT SPECIFIC_NAME,ORDINAL_POSITION,PARAMETER_MODE,PARAMETER_NAME,DTD_IDENTIFIER,CHARACTER_SET_NAME,COLLATION_NAME
 FROM information_schema.PARAMETERS WHERE SPECIFIC_SCHEMA='secure_payroll' ORDER BY SPECIFIC_NAME,ORDINAL_POSITION;
SELECT TRIGGER_NAME,EVENT_OBJECT_TABLE,ACTION_TIMING,EVENT_MANIPULATION,DEFINER,ACTION_STATEMENT
 FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='secure_payroll' ORDER BY EVENT_OBJECT_TABLE,TRIGGER_NAME;
